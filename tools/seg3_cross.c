static int read_list(const char*path,char (*buf)[25],int want,int*count){
    FILE*f=fopen(path,"r"); if(!f){ fprintf(stderr,"cannot open %s\n",path); exit(2); }
    char line[256]; int n=0, dropped=0;
    while(fgets(line,sizeof line,f)){
        size_t L=strlen(line); while(L&&(line[L-1]=='\n'||line[L-1]=='\r')) line[--L]=0;
        if(!L) continue;
        if((int)L!=want){ dropped++; continue; }
        for(int i=0;i<want;i++) buf[n][i]=(char)(line[i]>='A'&&line[i]<='Z'?line[i]+32:line[i]);
        buf[n][want]=0; n++;
    }
    fclose(f);
    if(dropped) fprintf(stderr,"%s: dropped %d line(s) not exactly %d chars\n",path,dropped,want);
    *count=n; return n;
}

