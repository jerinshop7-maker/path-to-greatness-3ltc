/*
 * seg3_cross.c -- segment 3 padding-oracle search over the two key halves.
 *
 * Segment 3's AES-256 key is clue3 (8 characters) || clue7 (24 characters).
 * The plaintext is one block: 8 useful bytes followed by PKCS7 padding of
 * eight 0x08 bytes, so a key is correct iff
 *
 *     D(ct)[i] XOR iv[i] == 0x08   for i = 8..15
 *
 * That is a 64-bit condition on the output of one AES-256 block decryption.
 * The round function does not separate across the two halves of the key, so
 * there is no algebraic shortcut and the search is brute force.
 *
 * WHY THIS TOOL EXISTS. Clue 3 is closed as a source of new readings
 * (tools/clue3_closure.py: the printed digits are redundant on all 96 arrow
 * cells, the 92-cycle string hides no message, and every 8-character extraction
 * consistent with the step-size semantics has been enumerated). So the only way
 * to test a clue-7 candidate ON ITS OWN is to let the clue-3 half range over
 * everything it could be. Earlier runs let it range over {w,a,s,d}^8 (65,536)
 * and {0-9}^8 (100,000,000). Neither contains a MIXED answer, and all 1,290
 * retained clue-3 readings are mixed -- including the repo's own strongest,
 * `d3w1as24`, which needs letters and digits. Every clue-7 negative in rounds
 * 14-20 was therefore computed against a clue-3 space that could not have held
 * the answers it was testing for.
 *
 * This tool sweeps the full
 *
 *     "wasd0123456789" ^ 8 = 1,475,789,056
 *
 * so a clue-7 candidate that fails here is refuted UNCONDITIONALLY, rather than
 * conditionally on a clue-3 reading being right.
 *
 * Modes
 *   list  <witness-file> <lefts> <rights>
 *          cross product of two files, one string per line. Every pair is a
 *          real candidate pair, so a hit names both halves.
 *   alpha <witness-file> <rights> [max_rights]
 *          for each right, sweep the clue-3 half over the full alphabet above.
 *   pt    <keys>
 *          print key and full plaintext for each 32-char key line, so an
 *          external implementation can be compared byte for byte.
 *
 * Witness protocol. Both searching modes take a witness file generated by
 * tools/seg3_witnesses.py using pycryptodome, and re-check every witness
 * before the sweep starts. A run that cannot re-find them prints UNCERTIFIED
 * and its negatives do not count. Witness keys are drawn from the streams
 * actually swept, so a hit inside a real family is guaranteed re-findable by
 * that same run.
 *
 * This file contains DECRYPTION ONLY. An earlier version also carried a forward
 * cipher in order to plant witnesses in-process; its decrypt agreed with
 * pycryptodome while its encrypt did not, so the forward cipher was removed
 * rather than trusted. Witness generation now lives in
 * tools/seg3_witnesses.py, which shares no code with this file.
 *
 * usage
 *   seg3_cross selftest
 *   seg3_cross pt    <keys.txt>
 *   seg3_cross list  <witnesses.txt> <lefts.txt> <rights.txt>
 *   seg3_cross alpha <witnesses.txt> <rights.txt> [max_rights]
 */
