#define MAXW 32
static uint8_t WKEY[MAXW][33]; /* 32 ASCII characters plus a NUL for printing */
static uint8_t WCT[MAXW][16]; static char WNAME[MAXW][32];
static int nw;
static void read_witnesses(const char*path){
    FILE*f=fopen(path,"r"); if(!f){ fprintf(stderr,"cannot open %s\n",path); exit(2); }
    char line[256];
    while(fgets(line,sizeof line,f) && nw<MAXW){
        char name[32],key[64],ct[64];
        if(sscanf(line,"%31s %63s %63s",name,key,ct)!=3) continue;
        if(strlen(key)!=32||strlen(ct)!=32){ fprintf(stderr,"bad witness line: %s",line); continue; }
        snprintf(WNAME[nw],32,"%s",name);
        memcpy(WKEY[nw],key,32); WKEY[nw][32]=0;
        hexdecode(ct,WCT[nw]);
        nw++;
    }
    fclose(f);
    if(!nw){ fprintf(stderr,"witness file %s has no usable lines\n",path); exit(2); }
}
static int verify_witnesses(void){
    int ok=0;
    for(int i=0;i<nw;i++){
        uint8_t pt[16], save[16];
        memcpy(save,CT,16);
        memcpy(CT,WCT[i],16);
        int hit=test_key(WKEY[i],pt);
        memcpy(CT,save,16);
        printf("witness %-10s key=%s  padding %s",WNAME[i],(const char*)WKEY[i],
               hit?"OK":"FAILED");
        if(hit){ show_pt(pt); ok++; } else printf("\n");
    }
    printf("witnesses re-found: %d/%d %s\n",ok,nw,ok==nw?"OK":"-- UNCERTIFIED");
    return ok;
}

/* ---------------------------------------------------------------- selftest */
static int selftest(void){
    int ok=1;
    /* Re-derive the S-box from its definition and require all 256 bytes. */
    {
        uint8_t inv_tbl[256], S[256];
        int have_all=1;
        memset(inv_tbl,0,sizeof inv_tbl);   /* inv_tbl[0] = 0: never set below */
        for(int a=1;a<256;a++){
            int found=0;
            for(int b=1;b<256;b++){
                uint8_t r=0, aa=(uint8_t)a, bb=(uint8_t)b;
                while(bb){ if(bb&1) r^=aa; aa=MUL1[aa]; bb>>=1; }
                if(r==1){ inv_tbl[a]=(uint8_t)b; found=1; break; }
            }
            if(!found){ printf("  no GF(2^8) inverse for %d\n",a); have_all=0; }
        }
        for(int i=0;i<256;i++){
            uint8_t x=inv_tbl[i], y=x, acc=x;
            for(int sh=1;sh<=4;sh++){ y=(uint8_t)((y<<1)|(y>>7)); acc^=y; }
            S[i]=(uint8_t)(acc^0x63);
        }
        int t=have_all;
        for(int i=0;i<256;i++) if(S[i]!=SBOX[i]) t=0;
        printf("S-box equals affine(GF(2^8) inverse), 256/256      -> %s\n",t?"OK":"FAIL");
        ok&=t;
        int u=1; for(int i=0;i<256;i++) if(ISBOX[SBOX[i]]!=i) u=0;
        printf("ISBOX is the exact inverse of SBOX, 256/256       -> %s\n",u?"OK":"FAIL");
        ok&=u;
        int v=1; for(int i=0;i<256;i++) if(SBOX[ISBOX[i]]!=i) v=0;
        printf("SBOX is the exact inverse of ISBOX, 256/256       -> %s\n",v?"OK":"FAIL");
        ok&=v;
    }
    /* a pycryptodome vector, supplied by tools/seg3_witnesses.py --selftest */
    {
        uint8_t key[32],pt[16],ct[16],out[16],rk[240];
        hexdecode("1bad420c0aa898aa5485483e92cd5d3a0af14dd7516d148eb6602ad6434bf064",key);
        hexdecode("502414db284e8198f5bf7af67344af2a",pt);
        hexdecode("ff741e83ed1f12662dbebacb7cb56483",ct);
        aes256_expand(key,rk);
        aes256_decrypt_block(rk,ct,out);
        int t=1; for(int i=0;i<16;i++) if(out[i]!=pt[i]) t=0;
        printf("pycryptodome AES-256 decrypt                         -> %s\n",t?"OK":"FAIL");
        ok&=t;
    }
    /* the four real segment ciphertexts: 16 bytes, 16-char IV, and base64
       canonicity (a 16-byte value leaves only 2 useful bits in character 22,
       so it can only be A, Q, g or w) */
    {
        int t=1;
        for(int s=1;s<=4;s++){
            uint8_t b[32]; int n=0; b64decode(SEG_CT_B64[s],b,&n);
            int c22=SEG_CT_B64[s][21];
            int good=n==16 && strlen(SEG_IV[s])==16 && strchr("AQgw",c22)!=NULL;
            printf("segment %d  ct=%d bytes  iv=%zu chars  base64[21]=%c      -> %s\n",
                   s,n,strlen(SEG_IV[s]),c22,good?"OK":"FAIL");
            t&=good;
        }
        printf("segment parameters                                  -> %s\n",t?"OK":"FAIL");
        ok&=t;
    }
    /* an arbitrary key must be rejected */
    {
        int n; b64decode(SEG_CT_B64[3],CT,&n); memcpy(IV,SEG_IV[3],16);
        uint8_t key[32];
        for(int i=0;i<32;i++) key[i]=(uint8_t)(i*7+1);
        int t = test_key(key,NULL) ? 0 : 1;
        printf("an arbitrary 32-byte key is rejected                 -> %s\n",t?"OK":"FAIL");
        ok&=t;
    }
    printf("%s\n",ok?"SELFTEST OK":"SELFTEST FAILED, conclude nothing");
    return ok;
}

/* --------------------------------------------------------- cross-check mode */
static int mode_pt(const char*path){
    int n; b64decode(SEG_CT_B64[3],CT,&n); memcpy(IV,SEG_IV[3],16);
    FILE*f=fopen(path,"r"); if(!f){ fprintf(stderr,"cannot open %s\n",path); return 2; }
    char line[256]; long count=0;
    while(fgets(line,sizeof line,f)){
        size_t L=strlen(line); while(L&&(line[L-1]=='\n'||line[L-1]=='\r')) line[--L]=0;
        if(!L) continue;
        if(L!=32){ fprintf(stderr,"skipping %zu-char line\n",L); continue; }
        uint8_t key[32]; memcpy(key,line,32);
        uint8_t rk[240],out[16],pt[16];
        aes256_expand(key,rk);
        aes256_decrypt_block(rk,CT,out);
        for(int i=0;i<16;i++) pt[i]=(uint8_t)(out[i]^IV[i]);
        printf("%s ",line);
        for(int i=0;i<16;i++) printf("%02x",pt[i]);
        printf(" %s\n", (memcmp(pt+8,"\x08\x08\x08\x08\x08\x08\x08\x08",8)==0)?"PAD":"");
        count++;
    }
    fclose(f);
    fprintf(stderr,"printed %ld plaintexts\n",count);
    return 0;
}

/* --------------------------------------------------------------- list mode */
static int mode_list(const char*wf,const char*lf,const char*rf){
    int n; b64decode(SEG_CT_B64[3],CT,&n); memcpy(IV,SEG_IV[3],16);
    read_witnesses(wf);
    if(verify_witnesses()!=nw) return 1;

    LEFT =calloc(400000,sizeof *LEFT);
    RIGHT=calloc(400000,sizeof *RIGHT);
    if(!LEFT||!RIGHT){ fprintf(stderr,"out of memory\n"); return 2; }
    read_list(lf,LEFT,8,&nleft);
    read_list(rf,RIGHT,24,&nright);
    if(!nleft||!nright){ printf("nothing to test\n"); return 0; }
    fprintf(stderr,"list mode: %d lefts x %d rights = %lld pairs\n",
            nleft,nright,(long long)nleft*nright);

    unsigned long long tried=0; int hits=0;
    for(int i=0;i<nleft;i++)
        for(int j=0;j<nright;j++){
            uint8_t key[32]; memcpy(key,LEFT[i],8); memcpy(key+8,RIGHT[j],24);
            uint8_t pt[16];
            tried++;
            if(test_key(key,pt)){
                hits++;
                printf("HIT  wasd=%s  ship=%s\n",LEFT[i],RIGHT[j]);
                show_pt(pt); fflush(stdout);
            }
        }
    printf("list: %llu pairs, %d hit(s)\n",tried,hits);
    printf("RESULT %s\n",hits?"HIT":"no match");
    return hits?0:1;
}

/* -------------------------------------------------------------- alpha mode */
static int mode_alpha(const char*wf,const char*rf,long max_rights){
    int n; b64decode(SEG_CT_B64[3],CT,&n); memcpy(IV,SEG_IV[3],16);
    read_witnesses(wf);
    if(verify_witnesses()!=nw) return 1;

    RIGHT=calloc(400000,sizeof *RIGHT);
    if(!RIGHT){ fprintf(stderr,"out of memory\n"); return 2; }
    read_list(rf,RIGHT,24,&nright);
    if(max_rights>0 && nright>max_rights) nright=(int)max_rights;
    if(!nright){ printf("nothing to test\n"); return 0; }
    fprintf(stderr,"alpha mode: %d rights x 14^8 = %.4g keys\n",
            nright,(double)nright*1475789056.0);

    /* report which witnesses sit inside the stream this sweep will traverse */
    int wi=nright/2;
    for(int i=0;i<nw;i++)
        if(!memcmp(WKEY[i],"wasdwasd",8) && !memcmp(WKEY[i]+8,RIGHT[wi],24))
            printf("witness '%s' lies inside the alpha sweep stream\n",WNAME[i]);

    unsigned long long total=0; int hits=0;
    uint8_t idx[8];
    for(int j=0;j<nright;j++){
        uint8_t key[32]; memcpy(key+8,RIGHT[j],24);
        memset(idx,0,8);
        for(;;){
            for(int k=0;k<8;k++) key[k]=(uint8_t)ALPHA[idx[k]];
            total++;
            uint8_t pt[16];
            if(test_key(key,pt)){
                hits++;
                printf("HIT  wasd=%.8s  ship=%s\n",(const char*)key,RIGHT[j]);
                show_pt(pt); fflush(stdout);
            }
            int d=7;
            while(d>=0){ if(idx[d]<NALPHA-1){ idx[d]++; break; } idx[d]=0; d--; }
            if(d<0) break;
        }
        printf("  [%d/%d] ship=%s  %llu keys, %d hits\n",j+1,nright,RIGHT[j],total,hits);
        fflush(stdout);
    }
    printf("alpha: %llu keys, %d hit(s)\n",total,hits);
    printf("RESULT %s\n",hits?"HIT":"no match");
    return hits?0:1;
}

int main(int argc,char**argv){
    build_tables();
    if(argc<2){ fprintf(stderr,
        "usage: seg3_cross selftest\n"
        "       seg3_cross pt    <keys.txt>\n"
        "       seg3_cross list  <witnesses.txt> <lefts.txt> <rights.txt>\n"
        "       seg3_cross alpha <witnesses.txt> <rights.txt> [max_rights]\n"); return 2; }
    if(!strcmp(argv[1],"selftest")) return selftest()?0:1;
    if(!strcmp(argv[1],"pt")&&argc==3)    return mode_pt(argv[2]);
    if(!strcmp(argv[1],"list")&&argc==5)  return mode_list(argv[2],argv[3],argv[4]);
    if(!strcmp(argv[1],"alpha")&&argc>=4) return mode_alpha(argv[2],argv[3],argc>4?atol(argv[4]):0);
    fprintf(stderr,"bad arguments\n");
    return 2;
}