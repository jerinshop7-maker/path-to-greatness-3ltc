static int b64val(int c){
    if(c>='A'&&c<='Z') return c-'A';
    if(c>='a'&&c<='z') return c-'a'+26;
    if(c>='0'&&c<='9') return c-'0'+52;
    if(c=='+') return 62;
    if(c=='/') return 63;
    return -1;
}
static void b64decode(const char*s,uint8_t*out,int*n){
    int acc=0,bits=0,o=0;
    for(const char*p=s;*p&&*p!='=';p++){
        acc=(acc<<6)|b64val(*p); bits+=6;
        if(bits>=8){ bits-=8; out[o++]=(uint8_t)((acc>>bits)&0xff); }
    }
    *n=o;
}
static int hexnib(int c){
    if(c>='0'&&c<='9') return c-'0';
    if(c>='a'&&c<='f') return c-'a'+10;
    if(c>='A'&&c<='F') return c-'A'+10;
    return -1;
}
static void hexdecode(const char*s,uint8_t*out){
    size_t n=strlen(s)/2;
    for(size_t i=0;i<n;i++) out[i]=(uint8_t)(hexnib(s[2*i])*16+hexnib(s[2*i+1]));
}

static uint8_t CT[16], IV[16];
/* clue 3 is lowercased and 8 characters. The clue's own grid uses only w,a,s,d
   and the digits 1-9; 0 is included because a step count of 0 is a legitimate
   reading of "no movement", so the sweep must not quietly assume otherwise. */
static const char* ALPHA = "wasd0123456789";
#define NALPHA 14

static inline int test_key(const uint8_t*key,uint8_t*pt){
    uint8_t rk[240],out[16];
    aes256_expand(key,rk);
    aes256_decrypt_block(rk,CT,out);
    for(int i=8;i<16;i++) if((uint8_t)(out[i]^IV[i])!=0x08) return 0;
    if(pt) for(int i=0;i<16;i++) pt[i]=(uint8_t)(out[i]^IV[i]);
    return 1;
}
static void show_pt(const uint8_t*pt){
    printf("  super_key bytes 16-23 = ");
    for(int i=0;i<8;i++) printf("%02x",pt[i]);
    printf("  ascii8=%.*s\n",8,(const char*)pt);
}

